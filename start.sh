#!/bin/bash
set -eu

# Multica on Cloudron. Runs as root for setup, then hands the backend, the web app and nginx to
# supervisor (all drop to the `cloudron` user).
#
#   /app/data/env.sh     operator settings (who may sign in, integrations); edit + restart
#   /app/data/.secrets   generated once; never regenerated, or sessions and stored tokens break
#   /app/data/uploads    attachments (local storage)

SECRETS=/app/data/.secrets/secrets.env

# Root must never act on paths the app user (cloudron) can rename or replace, or a compromised app
# could plant symlinks and steer the root steps below. So /app/data is root-owned, env.sh is
# root-owned and only readable by the app, the app owns only uploads/, and /run/multica is
# recreated, root-owned, on every start.
echo "==> Securing data directories"
chown root:root /app/data
chmod 755 /app/data
for path in /app/data/env.sh /app/data/.secrets "${SECRETS}" /app/data/uploads; do
    if [[ -L "${path}" ]]; then
        echo "==> ERROR: ${path} is a symbolic link, which this package never creates. Refusing to start."
        echo "    Inspect it from the web terminal, remove the link and restart."
        sleep 30
        exit 1
    fi
done
if [[ -e /app/data/env.sh && ! -f /app/data/env.sh ]]; then
    echo "==> ERROR: /app/data/env.sh should be a regular file. Refusing to start."
    sleep 30
    exit 1
fi
for dir in /app/data/.secrets /app/data/uploads; do
    if [[ -e "${dir}" && ! -d "${dir}" ]]; then
        echo "==> ERROR: ${dir} should be a directory. Refusing to start."
        sleep 30
        exit 1
    fi
done
mkdir -p /app/data/.secrets /app/data/uploads
chown root:root /app/data/.secrets
chmod 700 /app/data/.secrets
# Check the secrets file again now that the app user can no longer write into its directory.
if [[ -L "${SECRETS}" ]] || [[ -e "${SECRETS}" && ! -f "${SECRETS}" ]]; then
    echo "==> ERROR: ${SECRETS} is not a regular file. Refusing to start."
    sleep 30
    exit 1
fi

echo "==> Setting up runtime directories"
rm -rf /run/multica
mkdir -p /run/multica/home /run/multica/tmp /run/multica/nginx
chmod 755 /run/multica
chown cloudron:cloudron /run/multica/home /run/multica/tmp /run/multica/nginx

if [[ ! -f /app/data/env.sh ]]; then
    echo "==> First run: writing /app/data/env.sh template"
    cat > /app/data/env.sh <<'EOF'
# Multica settings. Restart the app after editing (Cloudron dashboard -> Restart).
# Reference: SELF_HOSTING.md / SELF_HOSTING_ADVANCED.md / .env.example in github.com/multica-ai/multica
#
# Set by the package on every start (values here are ignored): the database, the public URLs and
# allowed origins, outgoing email (Cloudron's mail server), local file storage, the port layout
# and DO_NOT_TRACK (telemetry off).

# --- Who may sign in -----------------------------------------------------------------------
# Sign-in is by a code sent by email (or Google, below). Sign-up is closed by default: only the
# addresses or domains listed here, and people invited to a workspace, can create an account.
# Set at least one before the first sign-in.
ALLOWED_EMAILS=""                   # e.g. "me@example.com,colleague@example.com"
ALLOWED_EMAIL_DOMAINS=""            # e.g. "example.com"
# ALLOW_SIGNUP="false"              # "true": anyone may sign up (not recommended)
# DISABLE_WORKSPACE_CREATION="false"

# --- Optional: Google sign-in ---------------------------------------------------------------
# Redirect URI to register at Google: https://<this app's domain>/auth/callback
# GOOGLE_CLIENT_ID=""
# GOOGLE_CLIENT_SECRET=""

# --- Optional integrations --------------------------------------------------------------------
# Self-hosted Forgejo / Gitea / GitLab is enabled (its encryption key is generated by the package).
# Each of the following is off until its key is set: a base64-encoded 32-byte key, e.g. from
#   openssl rand -base64 32
# MULTICA_SLACK_SECRET_KEY=""
# MULTICA_TELEGRAM_SECRET_KEY=""
# MULTICA_LARK_SECRET_KEY=""
# MULTICA_DINGTALK_SECRET_KEY=""
# MULTICA_WECOM_SECRET_KEY=""
# GitHub App (pull request mirroring):
# GITHUB_APP_SLUG=""
# GITHUB_APP_ID=""
# GITHUB_WEBHOOK_SECRET=""
# Server-side LLM for small helpers such as chat titles (off unless set):
# MULTICA_LLM_API_KEY=""
# MULTICA_LLM_BASE_URL=""
# MULTICA_LLM_DEFAULT_MODEL=""
EOF
fi

# Secrets are generated on first run only. When migrating an existing Multica, replace them with
# the old installation's values before the first start against the imported database.
if [[ ! -f "${SECRETS}" ]]; then
    echo "==> First run: generating secrets"
    ( umask 077; cat > "${SECRETS}" <<EOF
JWT_SECRET="$(openssl rand -hex 32)"
MULTICA_VCS_SECRET_KEY="$(openssl rand -base64 32)"
EOF
    )
fi
chown root:root "${SECRETS}"
chmod 600 "${SECRETS}"

# Both files may only contain plain assignments: NAME="value" or NAME='value', no $, backticks or
# backslashes inside double quotes, no "export", no leading spaces. env.sh is later sourced by the
# app user; anything that could run a command is refused.
check_env_file() {
    local file=$1 bad
    # Only space and tab count as blanks: grep's [[:space:]] would also accept vertical tab and
    # form feed, which bash does not treat as blanks, so "x"<VT>#$(cmd) would run cmd.
    local sp=$' \t'
    if grep -q $'\r' "${file}"; then
        echo "==> ERROR: ${file} has Windows (CRLF) line endings, which would corrupt the values."
        echo "    Re-save it with Unix (LF) line endings and restart."
        return 1
    fi
    if LC_ALL=C grep -q $'[\x01-\x08\x0b\x0c\x0e-\x1f\x7f]' "${file}"; then
        echo "==> ERROR: ${file} contains control characters. Remove them and restart."
        return 1
    fi
    if ! bash -n "${file}"; then
        echo "==> ERROR: ${file} has a syntax error (see above). Fix it and restart."
        return 1
    fi
    if bad=$(grep -nvE "^[${sp}]*(#.*)?$|^[A-Za-z_][A-Za-z0-9_]*=(\"[^\"\$\`\\]*\"|'[^']*'|[A-Za-z0-9_./:@,+-]*)([${sp}]+#.*)?[${sp}]*$" "${file}"); then
        echo "==> ERROR: ${file} may only contain NAME=\"value\" lines (quote every value; use single"
        echo "    quotes if it contains \$, \` or a backslash; no 'export', no leading spaces). Offending lines:"
        echo "${bad}" | cut -d: -f1 | sed 's/^/    line /'
        return 1
    fi
}

chown root:cloudron /app/data/env.sh
chmod 640 /app/data/env.sh
if ! check_env_file /app/data/env.sh || ! check_env_file "${SECRETS}"; then
    sleep 30
    exit 1
fi

# This script runs as root and never sources a file: values like NODE_OPTIONS, LD_PRELOAD or PATH
# would affect the root-run commands below. Values it needs are read as text, by name; env.sh is
# loaded by app-env.sh, as the cloudron user, right before each process starts.
file_value() {
    # Quoted value: take what is inside the quotes (a "#" there is part of the value); unquoted:
    # drop a trailing " # comment". The validator has already restricted the line shapes.
    grep -E "^$2=" "$1" | tail -n 1 | cut -d= -f2- |
        sed -E "s/^\"([^\"]*)\".*/\1/; t; s/^'([^']*)'.*/\1/; t; s/[[:blank:]]+#.*$//"
}
for name in JWT_SECRET MULTICA_VCS_SECRET_KEY; do
    value=$(file_value "${SECRETS}" "${name}")
    if [[ ${#value} -lt 32 ]]; then
        echo "==> ERROR: ${name} is missing or too short in ${SECRETS}. Refusing to start."
        sleep 30
        exit 1
    fi
    export "${name}=${value}"
done

# Platform-derived settings: recomputed on every start because addon credentials and the app's
# domain can change.
case "${CLOUDRON_POSTGRESQL_URL}" in
    *\?*) export DATABASE_URL="${CLOUDRON_POSTGRESQL_URL}&sslmode=disable" ;;
    *)    export DATABASE_URL="${CLOUDRON_POSTGRESQL_URL}?sslmode=disable" ;;
esac
export APP_ENV=production
export FRONTEND_ORIGIN="${CLOUDRON_APP_ORIGIN}"
export CORS_ALLOWED_ORIGINS="${CLOUDRON_APP_ORIGIN}"
export MULTICA_APP_URL="${CLOUDRON_APP_ORIGIN}"
export MULTICA_PUBLIC_URL="${CLOUDRON_APP_ORIGIN}"
export MULTICA_DAEMON_SERVER_URL="${CLOUDRON_APP_ORIGIN}"
export GOOGLE_REDIRECT_URI="${CLOUDRON_APP_ORIGIN}/auth/callback"
# Same-origin layout: the web app reaches the backend on loopback; the browser uses relative URLs.
export REMOTE_API_URL="http://127.0.0.1:8080"
export LOCAL_UPLOAD_DIR=/app/data/uploads
# Only the local nginx (which replaces X-Forwarded-For with the client address) is trusted.
export MULTICA_TRUSTED_PROXIES="127.0.0.1/32"
# No telemetry, no managed-cloud features, no cookie sharing with sibling subdomains.
export DO_NOT_TRACK=1
export ANALYTICS_DISABLED=true
export MULTICA_CLOUD_URL=""
export COOKIE_DOMAIN=""
export MULTICA_DEV_VERIFICATION_CODE=""
export HOME=/run/multica/home
export TMPDIR=/run/multica/tmp
derived=(JWT_SECRET MULTICA_VCS_SECRET_KEY DATABASE_URL APP_ENV FRONTEND_ORIGIN CORS_ALLOWED_ORIGINS
    MULTICA_APP_URL MULTICA_PUBLIC_URL MULTICA_DAEMON_SERVER_URL GOOGLE_REDIRECT_URI REMOTE_API_URL
    LOCAL_UPLOAD_DIR MULTICA_TRUSTED_PROXIES DO_NOT_TRACK ANALYTICS_DISABLED MULTICA_CLOUD_URL
    COOKIE_DOMAIN MULTICA_DEV_VERIFICATION_CODE HOME TMPDIR)

# Outgoing email (sign-in codes, invitations) through Cloudron's mail server (sendmail addon;
# absent if outbound mail is disabled for the app). Multica (Go net/smtp) refuses to send the SMTP
# password over an unencrypted connection, so the plain port (CLOUDRON_MAIL_SMTP_PORT, 2525) fails
# with "smtp auth: unencrypted connection". Use the STARTTLS port instead. Its certificate is
# issued for the Cloudron dashboard domain, not for the internal host name "mail", so certificate
# verification is skipped; the connection stays encrypted and never leaves Cloudron's internal
# Docker network.
if [[ -n "${CLOUDRON_MAIL_SMTP_SERVER:-}" ]]; then
    export SMTP_HOST="${CLOUDRON_MAIL_SMTP_SERVER}"
    export SMTP_PORT="${CLOUDRON_MAIL_STARTTLS_PORT:-2587}"
    export SMTP_USERNAME="${CLOUDRON_MAIL_SMTP_USERNAME}"
    export SMTP_PASSWORD="${CLOUDRON_MAIL_SMTP_PASSWORD}"
    export SMTP_FROM_EMAIL="${CLOUDRON_MAIL_FROM}"
    export SMTP_TLS="starttls"
    export SMTP_TLS_INSECURE="true"
    export RESEND_API_KEY=""
    derived+=(SMTP_HOST SMTP_PORT SMTP_USERNAME SMTP_PASSWORD SMTP_FROM_EMAIL SMTP_TLS SMTP_TLS_INSECURE
        RESEND_API_KEY)
fi

# Hand secrets and derived values to app-env.sh, which applies them after env.sh so they win.
# The app processes get these values in their environment anyway, so the file is readable by them.
multica_env=$(mktemp /run/multica/.multica.env.XXXXXX)
for name in "${derived[@]}"; do
    printf '%s=%q\n' "${name}" "${!name}"
done > "${multica_env}"
chown root:cloudron "${multica_env}"
chmod 640 "${multica_env}"
mv -f "${multica_env}" /run/multica/multica.env

env_value() { file_value /app/data/env.sh "$1"; }

# Client addresses are only taken from Cloudron's reverse proxy, not from other containers.
proxy_ip=${CLOUDRON_PROXY_IP:-172.18.0.1}
if [[ ! "${proxy_ip}" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ && ! "${proxy_ip}" =~ ^[0-9a-fA-F]*:[0-9a-fA-F:]+$ ]]; then
    echo "==> WARNING: unexpected CLOUDRON_PROXY_IP '${proxy_ip}', using 172.18.0.1"
    proxy_ip=172.18.0.1
fi
printf 'set_real_ip_from %s;\n' "${proxy_ip}" > /run/multica/nginx-http.conf
chmod 644 /run/multica/nginx-http.conf

# Warnings only: read the values as text, without evaluating env.sh.
if [[ -z "$(env_value ALLOWED_EMAILS)" && -z "$(env_value ALLOWED_EMAIL_DOMAINS)" && "$(env_value ALLOW_SIGNUP)" != true ]]; then
    echo "==> NOTE: nobody can sign up yet. Set ALLOWED_EMAILS (or ALLOWED_EMAIL_DOMAINS) in /app/data/env.sh and restart."
fi
if [[ "$(env_value ALLOW_SIGNUP)" == true ]]; then
    echo "==> WARNING: ALLOW_SIGNUP is true: anyone who can reach this app can create an account."
fi
if [[ -z "${CLOUDRON_MAIL_SMTP_SERVER:-}" ]]; then
    echo "==> WARNING: outbound email is disabled, so sign-in codes cannot be sent."
fi

echo "==> Waiting for PostgreSQL"
for attempt in $(seq 1 60); do
    if pg_isready -q -h "${CLOUDRON_POSTGRESQL_HOST}" -p "${CLOUDRON_POSTGRESQL_PORT}" \
        -U "${CLOUDRON_POSTGRESQL_USERNAME}" -d "${CLOUDRON_POSTGRESQL_DATABASE}"; then
        break
    fi
    if [[ ${attempt} == 60 ]]; then
        echo "==> ERROR: PostgreSQL did not become ready in 2 minutes; exiting so Cloudron restarts the app."
        exit 1
    fi
    echo "==> PostgreSQL not ready yet (${attempt}/60)"
    sleep 2
done

# Backups and restores can reset ownership; chown -R does not follow symlinks inside these trees.
if ! chown -R cloudron:cloudron /app/data/uploads /app/code/web/apps/web/.next; then
    echo "==> WARNING: could not re-own every file under uploads/.next (continuing)"
fi

# The backend applies its database migrations itself (backend.sh) before it starts serving.
# Start supervisor with a clean environment: this script's secrets and Cloudron's addon
# credentials would otherwise be inherited by every program, nginx included. The app processes
# get what they need from env.sh and multica.env through app-env.sh.
echo "==> Starting Multica"
exec env -i PATH="${PATH}" LANG=C.UTF-8 \
    /usr/bin/supervisord --configuration /etc/supervisor/supervisord.conf --nodaemon
